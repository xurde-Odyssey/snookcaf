import { test, expect } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";
import { hashPassword } from "../../src/lib/auth/password";
const database = process.env.TEST_DATABASE_URL;
if (!database || !new URL(database).pathname.endsWith("_test")) throw new Error("Disposable test database required.");
const db = new PrismaClient({ datasourceUrl: database });
const password = "browser-test-only-password";
const staffEmail = `${randomUUID()}@phase3.test`; const adminEmail = `${randomUUID()}@phase3.test`;
const tableNumber = randomUUID().slice(0, 8);
let businessId: string;
const clock = (value: string) => writeFileSync(process.env.PHASE3_TEST_CLOCK_FILE!, value);
test.beforeAll(async () => {
  clock("2030-01-01T00:00:00.000Z");
  const b = await db.business.upsert({ where: { slug: "phase3-browser" }, update: {}, create: { slug: "phase3-browser", name: "Disposable browser tests" } }); businessId = b.id;
  const hash = await hashPassword(password);
  const admin = await db.staff.create({ data: { businessId, email: adminEmail, name: "Approval Admin", role: "ADMIN", passwordHash: hash, mustChangePassword: false } });
  await db.staff.create({ data: { businessId, email: staffEmail, name: "Table Staff", role: "STAFF", operationalArea: "TABLES", passwordHash: hash, mustChangePassword: false } });
  const last = await db.pricingVersion.findFirst({ where: { businessId }, orderBy: { version: "desc" } });
  await db.pricingVersion.create({ data: { businessId, version: (last?.version ?? 0) + 1, hourlyRate: "400", frameRate: "100", createdById: admin.id } });
  await db.snookerTable.create({ data: { businessId, number: tableNumber, name: "Browser test", defaultPlayType: "HOURLY" } });
});
test.afterAll(async () => { await db.$disconnect(); });
test("staff finishes 400 reference; admin approves 350; checkout remains pending and table is available", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill(staffEmail);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click(); await expect(page).toHaveURL("/");
  await page.goto("/tables");
  const table = page.getByTestId(`table-${tableNumber}`);
  await table.getByRole("button", { name: "Start session", exact: true }).click();
  const dialog = page.getByRole("dialog"); await expect(dialog).toBeVisible();
  clock("2030-01-01T00:30:00.000Z");
  await dialog.getByRole("button", { name: "Switch to frame-wise", exact: true }).click();
  await dialog.getByLabel("Completed frames — segment 2", { exact: true }).fill("2");
  await dialog.getByRole("button", { name: "Finish Session", exact: true }).click();
  await expect(dialog.getByTestId("reference-total")).toHaveText("Rs. 400");
  await dialog.getByLabel("Proposed final charge", { exact: true }).fill("350");
  await dialog.getByLabel("Adjustment reason", { exact: true }).fill("Customer service adjustment");
  await dialog.getByRole("button", { name: "Request admin approval", exact: true }).click();
  await expect(dialog.getByText("Waiting for an administrator", { exact: false })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Approve Custom Amount" })).toHaveCount(0);
  await dialog.getByRole("button", { name: "Cancel / Return to Session", exact: true }).click();
  await expect(table.getByText("Available", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Sign out", exact: true }).click(); await expect(page).toHaveURL("/login");
  await page.getByLabel("Email", { exact: true }).fill(adminEmail);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click(); await expect(page).toHaveURL("/");
  await page.goto("/pricing-reviews");
  const row = page.getByRole("row").filter({ hasText: `Table ${tableNumber}` });
  await row.getByRole("button", { name: "Review pricing", exact: true }).click();
  await dialog.getByLabel("Approved final charge", { exact: true }).fill("350");
  await dialog.getByLabel("Approval reason", { exact: true }).fill("Customer service adjustment");
  await dialog.getByRole("button", { name: "Approve Custom Amount", exact: true }).click();
  await expect(dialog.getByTestId("approved-total")).toHaveText("Rs. 350");
  await expect(dialog.getByTestId("reference-total")).toHaveText("Rs. 400");
  await expect(dialog.getByText("PENDING CHECKOUT", { exact: true })).toBeVisible();
  const saved = await db.snookerSession.findFirstOrThrow({ where: { businessId, tableNumber }, include: { checkout: true, adjustmentApprovedBy: true } });
  expect(saved.checkout?.status).toBe("PENDING"); expect(saved.checkout?.amount?.toString()).toBe("350");
  expect(saved.calculatedAmount?.toString()).toBe("400"); expect(saved.adjustmentApprovedBy?.email).toBe(adminEmail);
  expect(await db.sessionPricingEvent.count({ where: { sessionId: saved.id, action: "ADJUSTMENT_APPROVED" } })).toBe(1);
  expect(await db.auditLog.count({ where: { targetId: saved.id, action: "ADJUSTMENT_APPROVED" } })).toBe(1);
  expect(await db.snookerSession.count({ where: { tableId: saved.tableId, status: { in: ["RUNNING", "PAUSED"] } } })).toBe(0);
});
